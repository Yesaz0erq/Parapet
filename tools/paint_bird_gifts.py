"""Draw the cage brush, enrichment gifts and debris on the cage tray at 16×16."""
from pathlib import Path

from PIL import Image, ImageColor

TEXTURES = Path(__file__).resolve().parents[1] / "src/main/resources/assets/parapet/textures"


def sprite(path, palette, rows):
    colors = dict(zip("123456789abcdef", (ImageColor.getrgb("#" + h) for h in palette.split())))
    image = Image.new("RGBA", (16, 16))
    for y, row in enumerate(rows.strip("\n").splitlines()):
        for x, mark in enumerate(row):
            if mark != ".":
                image.putpixel((x, y), (*colors[mark], 255))
    destination = TEXTURES / (path + ".png")
    destination.parent.mkdir(parents=True, exist_ok=True)
    image.save(destination)


